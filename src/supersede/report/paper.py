"""Generate the paper's numbers and tables from ``results/``.

Every figure quoted in ``paper/main.tex`` comes from here, so the paper and the
experiments cannot drift apart. The output is:

* ``numbers.tex``: one value per key, used in the text as ``\\res{key}``. A key
  with no result yet prints as a red "??", so missing runs are visible.
* ``tab_*.tex``: tables, included with ``\\input``.
* ``provenance.tex``: which result file each section is built from, and the
  git revision of the code.

Usage:
    python -m supersede.report.paper --results results --data data/rfc --out paper/generated
"""

from __future__ import annotations

import argparse
import json
import math
import subprocess
from datetime import datetime
from pathlib import Path

from supersede.corpus import read_jsonl

POLICIES = ("none", "filter", "promote")
ANSWER_POLICIES = ("naive", "latest_only", "show_conflict")
RETRIEVERS = ("bm25", "dense", "hybrid")
METRICS = {
    "stale@1": "stale1",
    "stale_before_current": "sbc",
    "current@1": "current1",
    "current@10": "current10",
    "mrr_current": "mrr",
}


def tt(s: str) -> str:
    return r"\texttt{" + s.replace("_", r"\_") + "}"


def f3(x: float | None) -> str:
    return "--" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.3f}"


def f2(x: float | None) -> str:
    return "--" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.2f}"


def pct(x: float | None) -> str:
    return "--" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.1f}\\%"


def p0(x: float | None) -> str:
    """A share as a whole percentage, for prose."""
    return "--" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.0f}\\%"


def ci(pair, fmt=f3) -> str:
    return f"[{fmt(pair[0])}, {fmt(pair[1])}]" if pair else ""


class Numbers:
    def __init__(self) -> None:
        self.values: dict[str, str] = {}

    def __setitem__(self, key: str, value) -> None:
        if any(c in key for c in "\\{}#%"):
            raise ValueError(f"bad key {key!r}")
        self.values[key] = str(value)

    def tex(self) -> str:
        lines = ["% Generated by supersede.report.paper. Do not edit."]
        for k, v in sorted(self.values.items()):
            lines.append(rf"\expandafter\def\csname res@{k}\endcsname{{{v}}}")
        return "\n".join(lines) + "\n"


def load(path: Path):
    return json.loads(path.read_text()) if path.exists() else None


def table(spec: str, header: list[str], rows: list[list[str]], midrules=()) -> str:
    out = [rf"\begin{{tabular}}{{{spec}}}", r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    for i, r in enumerate(rows):
        if i in midrules:
            out.append(r"\midrule")
        out.append(" & ".join(r) + r" \\")
    out += [r"\bottomrule", r"\end{tabular}"]
    return "\n".join(out) + "\n"


def corpus_numbers(num: Numbers, data: Path) -> None:
    m = load(data / "manifest.json")
    if not m:
        return
    for k in (
        "n_docs",
        "n_docs_with_abstract",
        "n_supersession_edges",
        "n_superseded_docs",
        "n_update_edges",
        "n_components",
        "max_component_size",
        "n_queries",
    ):
        num[f"corpus.{k}"] = f"{m[k]:,}".replace(",", "{,}")
    for split, n in m["n_queries_by_split"].items():
        num[f"corpus.n_queries.{split}"] = f"{n:,}".replace(",", "{,}")
    num["corpus.sha"] = m["index_sha256"][:12]
    num["corpus.built"] = m["built_at"][:10]


def retrieval(num: Numbers, res: Path, files: dict) -> dict[str, str]:
    tables = {}
    r = load(res / "rfc_staleness_test.json")
    if r:
        files["Retrieval staleness (title queries)"] = "rfc_staleness_test.json"
        rows, rules = [], []
        for ret in RETRIEVERS:
            for var in ("new_title", "old_title"):
                if rows:
                    rules.append(len(rows)) if var == "new_title" else None
                for pol in POLICIES:
                    row = next(
                        (
                            x
                            for x in r["rows"]
                            if (x["retriever"], x["variant"], x["policy"]) == (ret, var, pol)
                        ),
                        None,
                    )
                    if row is None:
                        continue
                    for m, short in METRICS.items():
                        num[f"ret.{ret}.{var}.{pol}.{short}"] = f3(row[m])
                        num[f"ret.{ret}.{var}.{pol}.{short}.pct"] = p0(row[m])
                        num[f"ret.{ret}.{var}.{pol}.{short}.cipct"] = ci(row[f"{m}_ci95"], p0)
                        num[f"ret.{ret}.{var}.{pol}.{short}.ci"] = ci(row[f"{m}_ci95"])
                    num[f"ret.{var}.n"] = row["n"]
                    rows.append(
                        [
                            ret if pol == "none" and var == "new_title" else "",
                            var.replace("_", " ") if pol == "none" else "",
                            tt(pol),
                            f3(row["stale@1"]),
                            f3(row["current@1"]),
                            f3(row["current@10"]),
                            f3(row["mrr_current"]),
                        ]
                    )
        tables["tab_retrieval"] = table(
            "lllrrrr",
            [
                "retriever",
                "query",
                "policy",
                r"stale@1$\downarrow$",
                r"current@1$\uparrow$",
                r"current@10$\uparrow$",
                r"MRR$\uparrow$",
            ],
            rows,
            rules,
        )

    q = load(res / "rfc_questions_all.json")
    if q:
        files["Retrieval staleness (change-aware questions)"] = "rfc_questions_all.json"
        rows = []
        for ret in RETRIEVERS:
            for pol in POLICIES:
                row = next(
                    (x for x in q["rows"] if (x["retriever"], x["policy"]) == (ret, pol)), None
                )
                if row is None:
                    continue
                for m, short in METRICS.items():
                    num[f"qret.{ret}.{pol}.{short}"] = f3(row[m])
                    num[f"qret.{ret}.{pol}.{short}.pct"] = p0(row[m])
                    num[f"qret.{ret}.{pol}.{short}.cipct"] = ci(row[f"{m}_ci95"], p0)
                    num[f"qret.{ret}.{pol}.{short}.ci"] = ci(row[f"{m}_ci95"])
                num["qret.n"] = row["n"]
                rows.append(
                    [
                        ret if pol == "none" else "",
                        tt(pol),
                        f"{f3(row['stale@1'])} {ci(row['stale@1_ci95'])}",
                        f"{f3(row['current@1'])} {ci(row['current@1_ci95'])}",
                    ]
                )
        tables["tab_questions_retrieval"] = table(
            "llll",
            ["retriever", "policy", r"stale@1$\downarrow$ [95\% CI]", r"current@1$\uparrow$"],
            rows,
            (3, 6),
        )
    return tables


def questions(num: Numbers, data: Path, files: dict) -> dict[str, str]:
    m = load(data / "questions_manifest.json")
    if not m:
        return {}
    files["Question generation"] = "data/rfc/questions_manifest.json"
    num["qgen.prompt"] = m["prompt_version"]
    num["qgen.candidates"] = f"{m['n_candidate_edges']:,}".replace(",", "{,}")
    num["qgen.attempted"] = m["n_attempted"]
    num["qgen.accepted"] = m["n_accepted"]
    num["qgen.rate"] = pct(m["acceptance_rate"])
    o = m["outcomes"]
    num["qgen.skipped"] = o.get("skipped_by_model", 0)
    num["qgen.rejected"] = m["n_attempted"] - m["n_accepted"] - o.get("skipped_by_model", 0)
    rows = [[tt(k), str(v)] for k, v in sorted(o.items(), key=lambda kv: -kv[1])]
    return {"tab_qgen": table("lr", ["outcome", "pairs"], rows)}


def answers(num: Numbers, res: Path, files: dict) -> dict[str, str]:
    tables = {}
    rows = []
    for mode, name in (("std", "rfc_answer_staleness_hybrid.json"), ("blind", None)):
        name = name or "rfc_answer_staleness_hybrid_blind.json"
        r = load(res / name)
        if not r:
            continue
        files[f"Answer staleness ({'blind' if mode == 'blind' else 'standard'})"] = name
        num["ans.n"] = r["n_questions"]
        num["ans.answer_model"] = r["answer_backend"].split(":")[-1]
        num["ans.judge_model"] = r["judge_backend"].split(":")[-1]
        num["ans.context_k"] = r["context_k"]
        for pol in ANSWER_POLICIES:
            row = next((x for x in r["rows"] if x["policy"] == pol), None)
            if row is None:
                continue
            for m in ("stale_outcome", "current_outcome", "flagged_conflict", "abstain"):
                num[f"ans.{mode}.{pol}.{m}"] = pct(row[m])
                num[f"ans.{mode}.{pol}.{m}.ci"] = ci(row[f"{m}_ci95"], pct)
            rows.append(
                [
                    "blind" if mode == "blind" and pol == "naive" else "",
                    tt(pol),
                    f"{pct(row['stale_outcome'])} {ci(row['stale_outcome_ci95'], pct)}",
                    pct(row["current_outcome"]),
                    pct(row["flagged_conflict"]),
                    pct(row["abstain"]),
                ]
            )
    if rows:
        if len(rows) > 3:
            rows[0][0] = "standard"
        tables["tab_answers"] = table(
            "lllrrr",
            [
                "context",
                "policy",
                r"stale answer$\downarrow$ [95\% CI]",
                r"current$\uparrow$",
                "conflict flagged",
                "abstain",
            ],
            rows,
            (3,),
        )
    return tables


def judge(num: Numbers, res: Path, files: dict) -> None:
    from supersede.experiments.answer_staleness import kappa

    items = res / "rfc_answer_staleness_hybrid_items.jsonl"
    if not items.exists():
        return
    for key, name in (
        ("model", "rfc_answer_staleness_hybrid_labels_claude-opus-5-5.csv"),
        ("human", "rfc_answer_staleness_hybrid_human_check.csv"),
    ):
        path = res / name
        if not path.exists():
            continue
        try:
            k = kappa(path, items)
        except (ValueError, ZeroDivisionError):
            continue  # not labelled yet
        files[f"Judge agreement ({key} rater)"] = name
        num[f"judge.{key}.n"] = k["n"]
        num[f"judge.{key}.kappa"] = f2(k["kappa"])
        num[f"judge.{key}.agree"] = round(k["accuracy"] * k["n"])


def lineage(num: Numbers, res: Path, files: dict) -> dict[str, str]:
    r = load(res / "rfc_lineage_inference.json")
    if not r:
        return {}
    files["Lineage inference (librarian v0)"] = "rfc_lineage_inference.json"
    rows, rules = [], []
    for s in r:
        st = s["setting"]
        num[f"lin.{st}.ncand"] = f"{s['n_candidate_pairs']:,}".replace(",", "{,}")
        num[f"lin.{st}.recall"] = f3(s["candidate_recall"])
        num[f"lin.{st}.recall.pct"] = p0(s["candidate_recall"])
        num[f"lin.{st}.threshold"] = s["methods"]["logreg"]["threshold"]
        qsets = list(s["downstream"])
        if rows:
            rules.append(len(rows))
        for m in ("no_lineage", "heuristic", "logreg", "oracle"):
            e = s["methods"].get(m, {}).get("edges")
            if e:
                for k in ("precision", "recall", "f1"):
                    num[f"lin.{st}.{m}.{k}"] = f3(e[k])
            cells = [st if m == "no_lineage" else "", m.replace("_", " ")]
            cells += [f3(e[k]) for k in ("precision", "recall", "f1")] if e else ["--"] * 3
            for qs in qsets:
                d = s["downstream"][qs][m]
                key = "title" if qs.startswith("title") else "questions"
                num[f"lin.{st}.{m}.{key}.current1"] = f3(d["current@1"])
                num[f"lin.{st}.{m}.{key}.gap"] = f"{100 * d['gap_closed']:.0f}\\%"
                cells.append(f"{f3(d['current@1'])} ({100 * d['gap_closed']:.0f}\\%)")
            rows.append(cells)
    header = ["setting", "method", "edge P", "edge R", "edge F1"] + [
        f"{q}: current@1 (gap)" for q in qsets
    ]
    return {"tab_lineage": table("ll" + "rrr" + "r" * len(qsets), header, rows, rules)}


def model_alias(spec: str) -> str:
    return spec.split(":", 1)[-1].split("/")[-1].split(":")[0]


def agent(num: Numbers, res: Path, files: dict) -> dict[str, str]:
    runs = []
    for p in sorted((res / "agent" / "history").glob("*.json")):
        r = json.loads(p.read_text())
        if r.get("experiment") != "agent_lineage":
            continue
        runs.append((p, r))
    if not runs:
        return {}
    rows, log_rows = [], []
    cheap_done = set()
    for p, r in runs:
        files[f"Agent: {model_alias(r['model'])}, {r['prompt_version']}"] = (
            "agent/history/" + p.name
        )
        base = f"agent.{model_alias(r['model'])}.{r['prompt_version']}"
        num[f"{base}.n"] = r["n_sampled"]
        num[f"{base}.steps"] = f"{r['mean_steps']:.1f}"
        num[f"{base}.seconds"] = f"{r['mean_seconds']:.0f}"
        num["agent.prior.strict"] = f2(r["band_positive_rate"])
        num["agent.prior.lineage"] = f2(r["band_positive_rate_lineage"])
        num["agent.band"] = f"[{r['band'][0]}, {r['band'][1]})"
        num["agent.threshold"] = r["cheap_threshold"]
        sample_key = (r["setting"], r["n_sampled"], r.get("seed", 0))
        for truth, block in (("strict", r), ("lineage", r["lineage_truth"])):
            ms = [("agent", block["agent"])]
            if sample_key not in cheap_done:
                ms.insert(0, ("cheap", block["cheap_scorer"]))
            for who, m in ms:
                key = f"agent.cheap.{truth}" if who == "cheap" else f"{base}.{truth}"
                num[f"{key}.tpr"] = f2(m["tpr"])
                num[f"{key}.tnr"] = f2(m["tnr"])
                num[f"{key}.ba"] = f2(m["balanced_accuracy"])
                num[f"{key}.ba.ci"] = ci(m.get("balanced_accuracy_ci95"), f2)
                num[f"{key}.prec"] = f2(m["est_precision"])
        for truth, block in (("strict", r), ("lineage", r["lineage_truth"])):
            if sample_key not in cheap_done:
                m = block["cheap_scorer"]
                rows.append(
                    [
                        truth,
                        "cheap scorer (v0)",
                        "--",
                        f2(m["tpr"]),
                        f2(m["tnr"]),
                        f"{f2(m['balanced_accuracy'])} {ci(m.get('balanced_accuracy_ci95'), f2)}",
                        f2(m["est_precision"]),
                    ]
                )
            m = block["agent"]
            rows.append(
                [
                    truth,
                    "agent: " + tt(model_alias(r["model"])),
                    r["prompt_version"].replace("agent-", ""),
                    f2(m["tpr"]),
                    f2(m["tnr"]),
                    f"{f2(m['balanced_accuracy'])} {ci(m.get('balanced_accuracy_ci95'), f2)}",
                    f2(m["est_precision"]),
                ]
            )
        cheap_done.add(sample_key)
        log_rows.append(
            [
                tt(model_alias(r["model"])),
                r["prompt_version"],
                r["setting"],
                str(r["n_sampled"]),
                str(r["n_failed"]),
                f"{r['mean_steps']:.1f}",
                f"{r['mean_seconds']:.0f}",
                ", ".join(f"{k} {v}" for k, v in r["labels"].items()),
            ]
        )
    rows.sort(key=lambda x: (x[0] != "strict", "agent" in x[1], x[1], x[2]))
    split = next(i for i, x in enumerate(rows) if x[0] == "lineage")
    for i, x in enumerate(rows):
        if i not in (0, split):
            x[0] = ""
    return {
        "tab_agent": table(
            "lllrrlr",
            ["truth", "method", "prompt", "TPR", "TNR", "bal. acc. [95\\% CI]", "est. prec."],
            rows,
            (split,),
        ),
        "tab_agent_runs": table(
            "lllrrrrl",
            ["model", "prompt", "setting", "n", "failed", "steps", "s/pair", "labels"],
            log_rows,
        ),
    }


def agent_traces(res: Path) -> str:
    """Verbatim traces for each finished agent run: a correct positive, a correct
    negative and an error, when the run has them."""
    out = []
    for summary in sorted((res / "agent" / "history").glob("*.json")):
        r = json.loads(summary.read_text())
        log = summary.with_suffix(".jsonl")
        if r.get("experiment") != "agent_lineage" or not log.exists():
            continue
        rows = [x for x in read_jsonl(log) if x.get("label")]

        def first(cond, rows=rows):
            return next((x for x in rows if cond(x)), None)

        picks = [
            ("correct, supersedes", first(lambda x: x["gold"] and x["label"] == "supersedes")),
            ("correct, not", first(lambda x: not x["gold"] and x["label"] != "supersedes")),
            (
                "error",
                first(lambda x: bool(x["gold"]) != (x["label"] == "supersedes")),
            ),
        ]
        items = []
        for kind, x in picks:
            if x is None:
                continue
            steps = r"\newline ".join(
                _esc(t).replace("→", r"$\rightarrow$") for t in x.get("trace", [])
            )
            items.append(
                r"\item \textbf{"
                + kind
                + "}: "
                + tt(f"{x['old']} -> {x['new']}")
                + f" (gold {'supersedes' if x['gold'] else 'not'}; verdict {tt(x['label'])},"
                + f" confidence {x.get('confidence')}).\\\\ {{\\small\\ttfamily {steps}}}"
                + f"\\\\ \\emph{{{_esc(x.get('rationale', ''))}}}"
            )
        if items:
            out.append(
                r"\subsection*{"
                + tt(model_alias(r["model"]))
                + ", "
                + r["prompt_version"]
                + "}\n"
                + "\\begin{itemize}\n"
                + "\n".join(items)
                + "\n\\end{itemize}\n"
            )
    return "\n".join(out)


def _esc(s: str) -> str:
    out = []
    special = {
        "\\": r"\textbackslash{}",
        "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}",
    }
    for c in s:
        out.append(special.get(c) or ("\\" + c if c in "&%#_{}$" else c))
    return "".join(out)


def git_rev() -> str:
    try:
        rev = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
        dirty = subprocess.run(["git", "status", "--porcelain"], capture_output=True, text=True)
        return rev + ("+dirty" if dirty.stdout.strip() else "")
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def build(res: Path, data: Path, out: Path) -> dict[str, str]:
    num = Numbers()
    files: dict[str, str] = {}
    tables: dict[str, str] = {}
    corpus_numbers(num, data)
    tables |= retrieval(num, res, files)
    tables |= questions(num, data, files)
    tables |= answers(num, res, files)
    judge(num, res, files)
    tables |= lineage(num, res, files)
    tables |= agent(num, res, files)
    tables["agent_traces"] = agent_traces(res)
    num["meta.rev"] = git_rev()
    num["meta.date"] = datetime.now().strftime("%Y-%m-%d")

    prov = table(
        "ll",
        ["section", r"source (under \texttt{results/} unless stated)"],
        [[k, tt(v)] for k, v in files.items()],
    )
    out.mkdir(parents=True, exist_ok=True)
    (out / "numbers.tex").write_text(num.tex())
    (out / "provenance.tex").write_text(prov)
    for name, body in tables.items():
        (out / f"{name}.tex").write_text(body)
    return num.values


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--results", type=Path, default=Path("results"))
    ap.add_argument("--data", type=Path, default=Path("data/rfc"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated"))
    args = ap.parse_args()
    values = build(args.results, args.data, args.out)
    print(f"{len(values)} numbers written to {args.out}")


if __name__ == "__main__":
    main()
