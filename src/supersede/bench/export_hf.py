"""Export the RFC benchmark as a Hugging Face dataset folder (JSONL + dataset card).

Configs:
  corpus      every RFC: title, abstract (as published, masked, strict), year,
              keywords and the lineage fields (hide them for lineage inference)
  lineage     supersession edges old -> new, with the split of their lineage
  queries     title queries (old/new title) with current and stale doc IDs
  questions   change-aware questions with current and stale reference answers
  pairs       candidate pairs for lineage inference (strict setting) with labels

Nothing is uploaded here; ``--push REPO`` does it explicitly.

Usage:
    python -m supersede.bench.export_hf --data data/rfc --out dist/hf/supersede-bench
    python -m supersede.bench.export_hf ... --push hatoum/supersede-bench --private
"""

from __future__ import annotations

