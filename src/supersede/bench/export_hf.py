LICENSE_NOTE = """\
- **RFC metadata and abstracts** (titles, abstracts, keywords, years, lineage fields)
  come from the RFC Editor's public index (`rfc-index.xml`) and remain subject to the
  [IETF Trust Legal Provisions](https://trustee.ietf.org/documents/trust-legal-provisions/)
  (TLP 5.0, §3.c): they are unmodified excerpts, each attributed to the IETF and identified
  by its RFC number (`doc_id`). Questions' `evidence_*` fields are verbatim excerpts too.
- **Annotations added here** (splits, queries, change-aware questions and answers,
  candidate pairs and labels) are released under CC BY 4.0.
- The change-aware questions and answers were generated by an LLM
  (`{qmodel}`, prompt `{qprompt}`) from the abstracts and filtered by deterministic checks."""


MASKING_SCRIPT = '''"""Derive the masked and strict views of the corpus (Supersede-Bench).

The dataset ships RFC abstracts verbatim (the IETF Trust Legal Provisions allow
unmodified excerpts, not modified text), so the leakage-controlled views are
computed locally with this script:

* masked: every RFC number in titles and abstracts becomes [REF];
* strict: also drops every sentence with obsolete/supersede/replace.

    from datasets import load_dataset
    from masking import apply
    corpus = load_dataset("hatoum/supersede-rfc", "corpus")["corpus"]
    strict = corpus.map(lambda r: apply(r, "strict"))
"""

import re

_RFC_NUMBER = re.compile(r"{rfc_number}", re.I)
_SUPERSESSION_VERB = re.compile(r"{verb}", re.I)
_SENTENCE = re.compile(r"{sentence}")


def mask_text(text: str) -> str:
    return _RFC_NUMBER.sub("[REF]", text)


def strip_supersession(text: str) -> str:
    return " ".join(s for s in _SENTENCE.split(text) if not _SUPERSESSION_VERB.search(s))


def apply(row: dict, setting: str) -> dict:
    """``row`` with ``title`` and ``abstract`` rewritten for ``setting``."""
    if setting == "declared":
        return row
    abstract = row["abstract"]
    if setting == "strict":
        abstract = strip_supersession(abstract)
    if setting not in ("masked", "strict"):
        raise ValueError(setting)
    return {{**row, "title": mask_text(row["title"]), "abstract": mask_text(abstract)}}
'''


def export(
    data: Path,
    out: Path,
    with_pairs: bool = True,
    results: Path | None = None,
    figures: Path | None = None,
) -> dict:
    docs = load_docs(data / "corpus.jsonl")
    graph = LineageGraph(docs)
    manifest = json.loads((data / "manifest.json").read_text())
    out.mkdir(parents=True, exist_ok=True)
    counts: dict[str, dict[str, int]] = {}

    corpus = []
    for d in docs:
        corpus.append(
            {
                "doc_id": d.doc_id,
                "title": d.title,
                "abstract": d.abstract,
                "keywords": list(d.keywords),
                "year": d.year,
                "status": d.status,
                "obsoletes": list(d.obsoletes),
                "obsoleted_by": list(d.obsoleted_by),
                "updates": list(d.updates),
                "updated_by": list(d.updated_by),
                "is_superseded": graph.is_superseded(d.doc_id),
                "current_versions": sorted(graph.current_versions(d.doc_id)),
            }
        )
    write_jsonl(out / "corpus" / "corpus.jsonl", corpus)
    counts["corpus"] = {"corpus": len(corpus)}

    edges = {"dev": [], "test": []}
    for old, new in graph.edges:
        comp = graph.component(old)
        edges[split_of(comp)].append(
            {"old": old, "new": new, "component": min(comp, key=_num), "split": split_of(comp)}
        )
    counts["lineage"] = _write_splits(out / "lineage", edges)

    queries = {"dev": [], "test": []}
    for q in read_jsonl(data / "queries.jsonl"):
        queries[q["split"]].append(q)
    counts["queries"] = _write_splits(out / "queries", queries)

    questions = {"dev": [], "test": []}
    qmanifest = {}
    if (data / "questions.jsonl").exists():
        qmanifest = json.loads((data / "questions_manifest.json").read_text())
        for q in read_jsonl(data / "questions.jsonl"):
            new = q["edge"][1]
            q = {**q, "reference_new_is_superseded": graph.is_superseded(new)}
            questions[q["split"]].append(q)
        counts["questions"] = _write_splits(out / "questions", questions)

    if with_pairs:
        from supersede.experiments.lineage_inference import candidates

        pairs, _ = candidates(masking.apply(docs, "strict"), data)
        gold = set(graph.edges)
        by_split = {"dev": [], "test": []}
        for old, new in pairs:
            s = split_of(graph.component(old))
            by_split[s].append(
                {
                    "old": old,
                    "new": new,
                    "label": int((old, new) in gold),
                    "label_lineage": int(new in graph.descendants(old)),
                    "split": s,
                }
            )
        counts["pairs"] = _write_splits(out / "pairs", by_split)

    (out / "masking.py").write_text(
        MASKING_SCRIPT.format(
            rfc_number=masking._RFC_NUMBER.pattern,
            verb=masking._SUPERSESSION_VERB.pattern,
            sentence=masking._SENTENCE.pattern,
        )
    )
    assets = copy_figures(figures, out / "assets") if figures else set()
    nums = card_numbers(results, data) if results else {}
    examples = {}
    if questions["test"]:
        # A short question about a concrete change (a mechanism, value or requirement).
        rank = {"mechanism": 0, "value": 0, "requirement": 0, "scope": 1}
        examples["questions"] = min(
            questions["test"],
            key=lambda q: (rank.get(q.get("change_type"), 2), len(json.dumps(q))),
        )
    if with_pairs:
        examples["pairs"] = next((r for r in by_split["test"] if r["label"]), None)
    (out / "README.md").write_text(
        card(manifest, qmanifest, counts, questions, nums, assets, examples)
    )
    return counts


def copy_figures(src: Path, dst: Path) -> set[str]:
    import shutil

    dst.mkdir(parents=True, exist_ok=True)
    done = set()
    for name in CARD_FIGURES:
        if (src / f"{name}.png").exists():
            shutil.copyfile(src / f"{name}.png", dst / f"{name}.png")
            done.add(name)
    return done


def _num(doc_id: str) -> int:
    return int("".join(c for c in doc_id if c.isdigit()) or 0)


def _write_splits(folder: Path, by_split: dict[str, list[dict]]) -> dict[str, int]:
    for split, rows in by_split.items():
        write_jsonl(folder / f"{split}.jsonl", rows)
    return {s: len(r) for s, r in by_split.items()}


